CREATE TABLE payment_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id VARCHAR(255) NOT NULL,
    order_id VARCHAR(255) NOT NULL,
    amount NUMERIC(19, 2) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    retry_count INTEGER NOT NULL DEFAULT 0,
    status VARCHAR(50) NOT NULL,
    failure_reason VARCHAR(255),
    next_retry_at TIMESTAMP,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    CONSTRAINT uk_payment_events_payment_id UNIQUE (payment_id)
);

CREATE INDEX idx_payment_events_status_next_retry_at
    ON payment_events (status, next_retry_at);

CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id VARCHAR(255),
    action VARCHAR(255),
    message VARCHAR(255),
    created_at TIMESTAMP
);

CREATE INDEX idx_audit_logs_payment_id_created_at
    ON audit_logs (payment_id, created_at);
